package Variables_DataTypes;

public class Concept2 {
    public static void main(String[] args) {
        //////////// topic - 02 [Variables] ////////////
        ///// Java has different types of variables, each with its own data type. Here are some examples of variables in Java: /////
        
        int a = 10; // integer variable
        float b = 20.5f; // float variable
        double c = 30.5; // double variable
        char d = 'A'; // character variable
        String e = "Hello"; // string variable
        boolean f = true; // boolean variable

        System.out.println("Integer value: " + a);
        System.out.println("Float value: " + b);
        System.out.println("Double value: " + c);
        System.out.println("Character value: " + d);
        System.out.println("String value: " + e);
        System.out.println("Boolean value: " + f);
    }
}
