package Variables_DataTypes;

public class Concept1{
    public static void main(String[] args) {
        //////////// topic - 01 [Output] ////////////
        System.out.print("Hello World");
        System.out.print("My name is Java");

        System.out.println();
        System.out.println("----------------------------------------------");

        /////////////// for printing it in next line -> use 'ln' function with print statement ////////////
        System.out.println("Hi");
        System.out.println("Hello");
        System.out.print("My name is Java");

        System.out.println();
        System.out.println("----------------------------------------------");

        /////////////we can also use "\n" instede of using 'ln' class /////////////////////
        System.out.print("Hi\n");
        System.out.print("Hello\n");
        System.out.print("My name is Java");

        System.out.println();
        System.out.println("----------------------------------------------");

        ///////////// we can also use "\n" inside of a line to print anything in next line /////////////////////
        System.out.print("Hi\nHello\nMy name is Java");
    }
}
